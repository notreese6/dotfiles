class ExitStatus(IntEnum):
    """
    Every process exit status the tools built on this library return, by the
    outcome each one stands for.

    An IntEnum because sys.exit() still needs a real int and comparisons still
    work unchanged, while the name is what a reader or a debugger sees. These
    values are the contract with whatever runs those tools, so they are pinned
    and never renumbered. 2 is deliberately absent: argparse produces it for a
    usage error and exits on its own, so nothing here ever returns it.

    An enum has no call signature of its own, so its members are documented in
    place of the Args/Returns/Raises contract a function carries.

    Members:
        OK: the command did what it was asked.
        NO_RULES_FOUND: every selected layer is absent or blank, so there was
            nothing to write.
        NO_KNOWN_AGENTS: not one configured agent name is recognized, so there
            was nowhere to write.
        BAD_AGENTS_SETTING: the `agents` setting is neither a name nor a list of
            names, so it could not be read at all. 5 is absent for the same kind of
            reason as 2: it reported a backup collision that timestamped backup
            directories made impossible.
        CLONE_FAILED: the configured local-rules remote could not be cloned, so
            setup stopped before writing any settings.
        MISSING_MODULE: a selected rules module has no file behind it. Nothing
            was written, because writing would silently drop that module's rules.
        SYNC_CONFLICT: a notes sync hit a real merge conflict. The rebase was
            aborted, so the working tree is exactly as it was, and a person has
            to decide which side wins.
        SYNC_LOCKED: another notes sync is already running against the same
            directory, so this one did nothing rather than interleave git
            commands with it.
        NOT_A_REPO: the notes directory is not a git repository. Nothing was
            created — making a repo out of someone's work is their decision.
    """

    OK                 = 0
    NO_RULES_FOUND     = 1
    NO_KNOWN_AGENTS    = 3
    BAD_AGENTS_SETTING = 4
    CLONE_FAILED       = 6
    MISSING_MODULE     = 7
    SYNC_CONFLICT      = 8
    SYNC_LOCKED        = 9
    NOT_A_REPO         = 10


class RulesRoot(Enum):
    """
    Which directory a supported agent's rules file is resolved against.

    The member values are auto-assigned and mean nothing on their own — they are
    never stored or compared, so a member only ever matches itself. Members are
    documented in place of the Args/Returns/Raises contract, as on ExitStatus
    above.

    Members:
        HOME: the user's home directory, where an agent that reads its rules off
            disk keeps them.
        CONFIG_DIR: the directory holding this tool's config file, where the text
            for an agent that reads no such file is parked instead.
    """

    HOME       = auto()
    CONFIG_DIR = auto()


@dataclass(frozen=True)
class SupportedAgent:
    """
    One agent this tool knows how to write a rules file for.

    Frozen because this describes what the tool supports rather than anything a
    run produces: the same record is read by every apply, so nothing should be
    able to edit it in place.

    Args:
        name (str): the name accepted in the `agents` setting, e.g. "claude".
        root (RulesRoot): which directory `relpath` is resolved against.
        relpath (tuple): (str, ...) the path parts under `root`, e.g.
            (".claude", "CLAUDE.md"). Never empty.
        needs_manual_paste (bool): True when writing the file is only half the
            job — the agent reads its rules out of its own settings UI rather
            than off disk, so the text still has to be pasted in by hand.
            Defaults to False, which is every agent that reads the file itself.

    Returns:
        None

    Raises:
        None
    """

    name:               str
    root:               RulesRoot
    relpath:            Tuple[str, ...]
    needs_manual_paste: bool = False

    def rules_path(self, roots):
        """
        Resolve the rules file this agent reads.

        The directories arrive keyed by RulesRoot rather than as one positional
        parameter each: both are plain paths, so a positional pair could be
        passed the wrong way round and would then resolve every agent under the
        wrong directory without any error to show for it.

        Args:
            roots (dict): {RulesRoot: pathlib.Path} the directory each root
                names. Must carry an entry for this agent's `root`. Callers
                resolve the whole mapping once, so every agent in a run is built
                against the same directories.

        Returns:
            pathlib.Path: `relpath` joined onto the directory `root` names.
            Absolute whenever that directory is. Not guaranteed to exist.

        Raises:
            KeyError: `roots` carries no entry for this agent's `root`.
        """

        return roots[self.root].joinpath(*self.relpath)


# Every agent this tool can write rules for, keyed by the name the `agents`
# setting uses so resolving one is a single lookup. Cursor has no rules file it
# reads on its own, so its text is parked beside the config for pasting in.
SUPPORTED_AGENTS = {
    agent.name: agent
    for agent in (
        SupportedAgent(name="claude", root=RulesRoot.HOME,       relpath=(".claude", "CLAUDE.md")),
        SupportedAgent(name="codex",  root=RulesRoot.HOME,       relpath=(".codex",  "AGENTS.md")),
        SupportedAgent(name="cursor", root=RulesRoot.CONFIG_DIR, relpath=("cursor-user-rules.txt",),
                       needs_manual_paste=True),
    )
}


class NoAgentsError(ValueError):
    """
    Not one configured agent name resolved to a rules file.

    Raised instead of writing nothing and returning quietly, because a run that
    writes zero files is indistinguishable from a successful one at the exit
    status. Callers report it and fail.

    Attributes:
        unknown (list): [str] the configured names that are not in
            SUPPORTED_AGENTS, in config order. Empty when `agents` was itself
            empty.
    """

    def __init__(self, unknown):
        """
        Record the unrecognized names next to the message.

        Args:
            unknown (iterable of str): configured names with no
                SUPPORTED_AGENTS entry.

        Returns:
            None

        Raises:
            None
        """

        self.unknown = list(unknown)

        super().__init__(f"no known agents configured: {', '.join(self.unknown) or '(none)'}")


class BadAgentsError(ValueError):
    """
    The `agents` setting is not an agent name, nor a list of them.

    A hand-edited config can end up holding `"agents": null`, `"agents": 5`, or
    a list with a non-string in it. Each of those reaches the write path and
    surfaces as a TypeError from somewhere deep inside it, so the shape is
    checked up front and reported as the configuration error it is.

    Attributes:
        value: the offending value — the setting itself when it is not a list,
            or the first element of that list which is not a string.
    """

    def __init__(self, value):
        """
        Record the offending value next to the message.

        Args:
            value: the setting, or the list element, that is not an agent name.

        Returns:
            None

        Raises:
            None
        """

        self.value = value

        super().__init__(f"invalid 'agents' setting: expected a name or a list of names, got {value!r}")


class EmptyRulesError(FileNotFoundError):
    """
    Every rules layer came back empty, so there is nothing to assemble.

    Reached when no module is selected and the private layer is absent, or when
    the selected modules exist but hold only whitespace. Assembling that yields
    a document with no rules in it, which would then replace every agent's live
    rules file, so it is refused instead. Subclasses FileNotFoundError because
    callers treat it exactly like missing input: there is nothing to apply.

    Attributes:
        path (pathlib.Path): the rules directory that produced nothing.
    """

    def __init__(self, path):
        """
        Name the empty file and say that nothing was written.

        Args:
            path (str or pathlib.Path): the rules directory that produced no
                text, or produced only whitespace.

        Returns:
            None

        Raises:
            None
        """

        self.path = Path(path)

        super().__init__(f"no rules selected or found, nothing was written: {self.path}")


class MissingModuleError(FileNotFoundError):
    """
    A selected rules module has no file behind it.

    Selecting a module and finding no file is a broken installation, not a
    preference: the config asked for those rules and they do not exist. Skipping
    it would assemble a document that is silently missing a whole discipline and
    then write that over every agent's live rules — a loss nobody sees, because
    the run still reports success. So the assembly refuses instead.

    Attributes:
        name (str): the module filename that was selected but absent.
        rules_dir (pathlib.Path): the directory that was searched.
    """

    def __init__(self, name, rules_dir):
        """
        Name the missing module, the directory searched, and what to do.

        Args:
            name (str): the selected module's filename, e.g. "daily-notes.md".
            rules_dir (str or pathlib.Path): the rules directory searched for it.

        Returns:
            None

        Raises:
            None
        """

        self.name      = name
        self.rules_dir = Path(rules_dir)

        super().__init__(
            f"selected rules module {name!r} is missing from {self.rules_dir}. "
            f"Restore the file, or turn the module off in the config"
        )


